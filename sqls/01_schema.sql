-- PostgreSQL 17 | UTF-8 | Estrutura inicial no schema public.
-- Executar uma vez, em banco sem estas tabelas. Não apaga tabelas existentes.
BEGIN;
SET LOCAL standard_conforming_strings = on;

CREATE TABLE public.categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT NOT NULL
);

CREATE TABLE public.customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT NOT NULL,
    city TEXT NOT NULL
);

CREATE TABLE public.products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_brl NUMERIC(12,2) NOT NULL CHECK (price_brl >= 0),
    name TEXT NOT NULL,
    category_id INTEGER NOT NULL REFERENCES public.categories(category_id),
    description TEXT NOT NULL,
    stock_quantity INTEGER NOT NULL CHECK (stock_quantity >= 0),
    status TEXT NOT NULL,
    specs JSONB NOT NULL,
    created_at DATE NOT NULL
);

CREATE TABLE public.orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL REFERENCES public.customers(customer_id),
    order_date DATE NOT NULL,
    status TEXT NOT NULL,
    total_brl NUMERIC(12,2) NOT NULL CHECK (total_brl >= 0),
    payment_method TEXT NOT NULL,
    tracking_code TEXT,
    estimated_delivery DATE,
    notes TEXT
);

CREATE TABLE public.order_items (
    order_id INTEGER NOT NULL REFERENCES public.orders(order_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    product_id INTEGER NOT NULL REFERENCES public.products(product_id),
    PRIMARY KEY (order_id, product_id)
);

CREATE TABLE public.promotions (
    promotion_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id INTEGER NOT NULL REFERENCES public.products(product_id),
    discount_percent NUMERIC(5,2) NOT NULL CHECK (discount_percent BETWEEN 0 AND 100),
    description TEXT NOT NULL,
    is_active BOOLEAN NOT NULL
);

-- Índices nas chaves estrangeiras; a PK composta já cobre order_items.order_id.
CREATE INDEX idx_products_category_id ON public.products(category_id);
CREATE INDEX idx_orders_customer_id ON public.orders(customer_id);
CREATE INDEX idx_order_items_product_id ON public.order_items(product_id);
CREATE INDEX idx_promotions_product_id ON public.promotions(product_id);

-- Status e métodos de pagamento são texto, permitindo novos valores.
-- Totais dos pedidos são preservados: o CSV não contém preço histórico por item.
-- Nenhuma promoção é vinculada a pedidos: essa informação não existe nas fontes.

-- Cada sessão tem várias mensagens. Sem dados fictícios de conversas na carga inicial.
CREATE TABLE public.chat_session (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.chat_history (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    session_id UUID NOT NULL REFERENCES public.chat_session(id),
    role TEXT NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Índice para filtro por sessão e intervalo de datas usado por get_chat_history.
CREATE INDEX idx_chat_history_session_created
    ON public.chat_history(session_id, created_at);

CREATE FUNCTION public.set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_chat_session_updated_at
BEFORE UPDATE ON public.chat_session
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TRIGGER trg_chat_history_updated_at
BEFORE UPDATE ON public.chat_history
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Inserir uma mensagem não dispara o trigger da sessão.
-- postgres_service deve continuar atualizando chat_session.updated_at explicitamente.
COMMIT;
